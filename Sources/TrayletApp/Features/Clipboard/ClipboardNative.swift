import AppKit

@MainActor final class V2ClipboardNativeSource: ClipboardSource {
    private let name: NSPasteboard.Name?
    private let application: () -> String?
    private var board: NSPasteboard { name.map(NSPasteboard.init(name:)) ?? .general }
    static let markerType = NSPasteboard.PasteboardType("local.traylet.v2.clipboard.self-write")
    static let blockedApplications = Set(["com.agilebits.onepassword7", "com.1password.1password", "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.dashlane.dashlane", "com.apple.passwords"])
    init(privatePasteboardName: NSPasteboard.Name? = nil, application: @escaping () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier }) {
        name = privatePasteboardName; self.application = application
    }
    var generation: Int { board.changeCount }
    func read(expectedGeneration: Int, excluding: Set<String>) -> V2ClipboardSnapshot? {
        read(expectedGeneration: expectedGeneration, excluding: excluding, policy: .init())
    }
    func read(expectedGeneration: Int, excluding: Set<String>, policy: ClipboardCapturePolicy) -> V2ClipboardSnapshot? {
        guard policy.hasEnabledType else { return nil }
        let pasteboard = board
        guard pasteboard.changeCount == expectedGeneration, let app = application(), !app.isEmpty,
              !excluding.contains(app), !Self.blockedApplications.contains(app.lowercased()) else { return nil }
        guard let nativeItems = pasteboard.pasteboardItems, !nativeItems.isEmpty, nativeItems.count <= 16 else { return nil }
        let itemTypes = nativeItems.map { Set($0.types.map(\.rawValue)) }
        // Preflight the whole multi-item copy, not just the first item, before any body request.
        for types in itemTypes {
            // Inspect type identifiers before materializing bodies; never request file or secret representations.
            let forbidden = types.contains { type in
                let value = type.lowercased()
                return value.contains("file") || value.contains("concealed") || value.contains("transient") || value.contains("autogenerated") || value.contains("password")
            }
            guard !forbidden, policy.allows(types) else { return nil }
        }
        var result: [ClipboardContent] = []; var total = 0; var marker: String?
        for (native, types) in zip(nativeItems, itemTypes) {
            // System conversion may advertise extra UTF-16 representations; only store the supported originals.
            if types.contains(Self.markerType.rawValue) { marker = native.string(forType: Self.markerType) }
            var representations: [String: Data] = [:]
            for type in types.intersection(ClipboardContent.allowed).sorted() {
                guard let data = native.data(forType: NSPasteboard.PasteboardType(type)) else { return nil }
                total += data.count; guard total <= ClipboardPolicy.itemBytes else { return nil }
                representations[type] = data
            }
            result.append(ClipboardContent(representations: representations))
        }
        guard pasteboard.changeCount == expectedGeneration, application() == app, ClipboardPolicy.valid(result) else { return nil }
        return V2ClipboardSnapshot(generation: expectedGeneration, items: result, application: app, marker: marker)
    }
}

/// All representations are prepared before the one destructive clear. Never retry or restore an old body.
@MainActor final class V2ClipboardNativeWriter: ClipboardWriting {
    private let name: NSPasteboard.Name?
    private let prepare: @MainActor ([ClipboardContent], String) -> [NSPasteboardItem]?
    private let afterClear: ((NSPasteboard) -> Void)?
    init(privatePasteboardName: NSPasteboard.Name? = nil,
         prepare: @escaping @MainActor ([ClipboardContent], String) -> [NSPasteboardItem]? = V2ClipboardNativeWriter.prepareItems,
         afterClear: ((NSPasteboard) -> Void)? = nil) {
        name = privatePasteboardName; self.prepare = prepare; self.afterClear = afterClear
    }
    static func prepareItems(_ items: [ClipboardContent], _ marker: String) -> [NSPasteboardItem]? {
        guard ClipboardPolicy.valid(items) else { return nil }
        var result: [NSPasteboardItem] = []
        for content in items {
            let item = NSPasteboardItem()
            for key in content.representations.keys.sorted() {
                guard item.setData(content.representations[key]!, forType: NSPasteboard.PasteboardType(key)) else { return nil }
            }
            guard item.setString(marker, forType: V2ClipboardNativeSource.markerType) else { return nil }
            result.append(item)
        }
        return result
    }
    func write(_ items: [ClipboardContent], marker: String) -> ClipboardWriteResult {
        guard let prepared = prepare(items, marker), prepared.count == items.count, !prepared.isEmpty else { return .failed }
        let board = name.map(NSPasteboard.init(name:)) ?? .general
        let generation = board.clearContents()
        afterClear?(board)
        guard board.changeCount == generation else { return .changed }
        let success = board.writeObjects(prepared)
        guard board.changeCount == generation else { return .changed }
        return success ? .copied(generation: generation) : .failed
    }
}
