import AppKit
import Testing
@testable import TrayletApp

@Suite("Clipboard Private Pasteboard") @MainActor struct ClipboardNativeTests {
    private func name() -> NSPasteboard.Name { .init("local.traylet.v2.test.\(UUID().uuidString)") }
    @Test func prepareFailureDoesNotClearAndRaceDoesNotClearAgain() throws {
        let name = name(); let board = NSPasteboard(name: name); defer { board.releaseGlobally() }
        board.clearContents(); try #require(board.setString("original synthetic", forType: .string), "Private pasteboard unavailable; no general fallback")
        let generation = board.changeCount
        let failed = V2ClipboardNativeWriter(privatePasteboardName: name, prepare: { _, _ in nil })
        #expect(failed.write([.text("new")], marker: "test") == .failed)
        #expect(board.changeCount == generation)
        #expect(board.string(forType: .string) == "original synthetic")
        let raced = V2ClipboardNativeWriter(privatePasteboardName: name, afterClear: { pasteboard in
            pasteboard.clearContents(); pasteboard.setString("external winner", forType: .string)
        })
        #expect(raced.write([.text("history")], marker: "test") == .changed)
        #expect(board.string(forType: .string) == "external winner")
    }
    @Test func writesAllRepresentationsAndReturnsExactGeneration() throws {
        let name = name(); let board = NSPasteboard(name: name); defer { board.releaseGlobally() }
        var item = ClipboardContent.text("synthetic plain")
        item.representations["public.html"] = Data("<b>synthetic</b>".utf8)
        item.representations["public.rtf"] = Data("{\\rtf1 synthetic}".utf8)
        let writer = V2ClipboardNativeWriter(privatePasteboardName: name)
        let result = writer.write([item, .text("second")], marker: "synthetic-marker")
        #expect(result == .copied(generation: board.changeCount))
        let source = V2ClipboardNativeSource(privatePasteboardName: name, application: { "synthetic.app" })
        let read = try #require(source.read(expectedGeneration: board.changeCount, excluding: []))
        #expect(read.items == [item, .text("second")])
        #expect(read.marker == "synthetic-marker")
        #expect(source.read(expectedGeneration: board.changeCount - 1, excluding: []) == nil)
        #expect(source.read(expectedGeneration: board.changeCount, excluding: ["synthetic.app"]) == nil)
    }
    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "public.file-url"])
    func secretOrFileMarkerRejectsWholeChange(_ type: String) throws {
        let name = name(); let board = NSPasteboard(name: name); defer { board.releaseGlobally() }
        let safe = NSPasteboardItem(); safe.setString("safe", forType: .string)
        let secret = NSPasteboardItem(); secret.setString("synthetic secret", forType: .string); secret.setData(Data(), forType: .init(type))
        board.clearContents(); try #require(board.writeObjects([safe, secret]), "Private pasteboard unavailable; no general fallback")
        let source = V2ClipboardNativeSource(privatePasteboardName: name, application: { "synthetic.app" })
        #expect(source.read(expectedGeneration: board.changeCount, excluding: []) == nil)
    }
    @Test func passwordManagerUnknownAppAndChangedFrontmostReject() throws {
        let name = name(); let board = NSPasteboard(name: name); defer { board.releaseGlobally() }
        board.clearContents(); try #require(board.setString("synthetic", forType: .string), "Private pasteboard unavailable; no general fallback")
        let manager = V2ClipboardNativeSource(privatePasteboardName: name, application: { "com.1password.1password" })
        #expect(manager.read(expectedGeneration: board.changeCount, excluding: []) == nil)
        let unknown = V2ClipboardNativeSource(privatePasteboardName: name, application: { nil })
        #expect(unknown.read(expectedGeneration: board.changeCount, excluding: []) == nil)
        var calls = 0
        let changing = V2ClipboardNativeSource(privatePasteboardName: name, application: { calls += 1; return calls == 1 ? "first.app" : "second.app" })
        #expect(changing.read(expectedGeneration: board.changeCount, excluding: []) == nil)
    }
}
